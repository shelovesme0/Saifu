import Foundation

/// Помилки мережевого шару. Інші типи помилок `HTTPClient` назовні не віддає.
enum NetworkError: Error {
    /// Запит не дійшов або відповідь не прийшла: немає інтернету, таймаут, DNS тощо.
    case transport(URLError)
    /// Сервер відповів, але статус не 2xx.
    case badStatus(Int)
    /// Тіло прийшло, але не відповідає очікуваному формату.
    case decoding(Error)
    /// Сервер відповів успішно, але даних немає (порожнє тіло або порожній список).
    case empty
}
